/* planets.test.mjs: rebuild wave 2 verification, the wanderers.
   Run: node tests/planets.test.mjs
   The reference (tests/planets-ref.json) is NASA JPL DE421 worked by
   Skyfield, generated by scripts/make_planet_ref.py: apparent geocentric
   positions of the date, altitudes and azimuths from plain geometry.
   Checks: (1) every wanderer stands within the stated tolerance of the
   ephemeris at 24 fixed cases (12 moments, two places); (2) determinism;
   (3) the set is the six naked-eye wanderers and no more; (4) magnitudes
   stay inside their physical bands; (5) no external address, no chance. */
import { planetRaDec, planetAltaz, WANDERERS } from "../assets/js/planets.js";
import fs from "fs";

let fails = 0;
const check = (name, ok) => { console.log((ok ? "ok  " : "FAIL") + " " + name); if (!ok) fails++; };

const ref = JSON.parse(fs.readFileSync(new URL("planets-ref.json", import.meta.url), "utf8"));
check("reference holds 24 cases from DE421", ref.cases.length === 24 && /DE421/.test(ref.source));
check("the wanderers are the six, in their order",
  JSON.stringify(WANDERERS) === JSON.stringify(["mercury", "venus", "mars", "jupiter", "saturn", "uranus"]));

/* Tolerances: the measured worst errors (mercury .012, venus .014, mars .012,
   jupiter .014, saturn .030, uranus .027 degrees of sky separation) with
   headroom, stated plainly: a twentieth of a degree of position, a
   twentieth in altitude, a fourteenth in azimuth (azimuth stretches near
   the zenith, where none of these cases puts a wanderer). */
const TOL_SEP = 0.05, TOL_ALT = 0.05, TOL_AZ = 0.07;
const worst = {};
/* Mercury's band runs wide on purpose: its phase polynomial is an observable-range
   fit, and past greatest elongation, running toward the sun's far side, it answers
   beyond its range (4.38 at the 2026-07-15 case). The drawing never shows a
   wanderer there: beside the sun is daylight, and the sky is gated on the dark. */
const BANDS = { mercury: [-2, 5], venus: [-5, -3], mars: [-3, 2], jupiter: [-3, -1], saturn: [-0.5, 1.5], uranus: [5, 6.5] };
let magOK = true;
for (const c of ref.cases) {
  const date = new Date(c.iso);
  const rd = planetRaDec(date), aa = planetAltaz(date, c.lat, c.lon);
  const byRd = {}, byAa = {};
  rd.forEach((p) => { byRd[p.name] = p; });
  aa.forEach((p) => { byAa[p.name] = p; });
  for (const name of WANDERERS) {
    const r = c.planets[name], a = byRd[name], b = byAa[name];
    let dra = Math.abs(a.ra - r.ra); dra = Math.min(dra, 360 - dra);
    const sep = Math.hypot(dra * Math.cos(r.dec * Math.PI / 180), a.dec - r.dec);
    let daz = Math.abs(b.az - r.az); daz = Math.min(daz, 360 - daz);
    const w = (worst[name] ??= { sep: 0, alt: 0, az: 0 });
    w.sep = Math.max(w.sep, sep); w.alt = Math.max(w.alt, Math.abs(b.alt - r.alt)); w.az = Math.max(w.az, daz);
    if (!(a.mag >= BANDS[name][0] && a.mag <= BANDS[name][1])) magOK = false;
  }
}
for (const name of WANDERERS) {
  const w = worst[name];
  check(name + " within tolerance of DE421 (worst: sep " + w.sep.toFixed(3) + ", alt " + w.alt.toFixed(3) + ", az " + w.az.toFixed(3) + " deg)",
    w.sep <= TOL_SEP && w.alt <= TOL_ALT && w.az <= TOL_AZ);
}
check("magnitudes stay inside their physical bands at every case", magOK);

/* Determinism: the reckoning is a pure function of the moment. */
const s1 = JSON.stringify(planetAltaz(new Date("2026-10-24T06:00:00Z"), 34.05, -118.24));
const s2 = JSON.stringify(planetAltaz(new Date("2026-10-24T06:00:00Z"), 34.05, -118.24));
check("determinism: same moment and place, byte-identical wanderers", s1 === s2);
const s3 = JSON.stringify(planetAltaz(new Date("2026-10-24T07:00:00Z"), 34.05, -118.24));
check("the wanderers move with the moment: one hour later differs", s1 !== s3);

/* No dependencies, no external address, no chance consulted. */
const src = fs.readFileSync(new URL("../assets/js/planets.js", import.meta.url), "utf8");
check("planets.js names no external address", !/https?:\/\//.test(src));
check("planets.js consults no chance and keeps no state", !/Math\.random|localStorage/.test(src));
const main = fs.readFileSync(new URL("../assets/js/main.js", import.meta.url), "utf8");
check("the seeded systems stand untouched (Wishfield, Nebula, Wrong Star)",
  main.includes("daySeed()*7+3") && main.includes("daySeed()*11+5") && main.includes("#9fd8b4") && main.includes("s.wrong? .92"));

console.log(fails ? fails + " FAILURES" : "all checks passed");
process.exit(fails ? 1 : 0);
